CREATE OR REPLACE FUNCTION public.handle_new_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
DECLARE 
  tipo public.tipo_perfil_enum;
  metadata jsonb;
BEGIN
  -- Captura os metadados com segurança
  metadata := NEW.raw_user_meta_data;
  
  IF metadata IS NULL THEN
    metadata := '{}'::jsonb;
  END IF;

  -- Define o tipo de perfil com base no CNPJ
  IF metadata ->> 'cnpj' IS NULL OR metadata ->> 'cnpj' = '' THEN 
    tipo := 'PESSOA_FISICA'; 
  ELSE 
    tipo := 'EMPRESA'; 
  END IF;

  -- Insere na tabela public.perfis
  INSERT INTO public.perfis 
  (id, tipo_perfil, nome_ou_razao, email, cnpj, foto_url, status) 
  VALUES (
    NEW.id, 
    tipo, 
    COALESCE(metadata ->> 'nome_ou_razao', 'Usuário'), 
    NEW.email, 
    metadata ->> 'cnpj', 
    metadata ->> 'foto_url', 
    'ATIVO'
  );

  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.trg_anonimizar_perfil()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
BEGIN
  -- Se o status mudar para EXCLUIDO, os dados são anonimizados (caminho sem volta)
  IF NEW.status = 'EXCLUIDO' AND OLD.status != 'EXCLUIDO' THEN
    NEW.nome_ou_razao := 'Usuário Excluído';
    NEW.email := 'excluido_' || NEW.id || '@sistema.com';
    NEW.cnpj := NULL;
    NEW.foto_url := NULL;
  END IF;
  
  -- Se mudar para AFASTADO, a Trigger não faz nada com os dados.
  -- Eles ficam intactos na tabela para o Admin poder resgatar mudando para ATIVO depois.
  RETURN NEW; 
END;
$function$;

